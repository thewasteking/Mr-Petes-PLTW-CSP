
import turtle as trtl
painter = trtl.Turtle()
painter.speed(0)
painter.color("green")
painter.pensize(15)
painter.goto(0, -130)
painter.setheading(90)
painter.forward(200)
painter.setheading(270)
painter.circle(20, 120, 20)
painter.setheading(90)
painter.goto(0, -60)
painter.forward(60)
painter.setheading(0)
painter.penup()
painter.shape("circle")
painter.turtlesize(2.5)
painter.color("darkorchid")
painter.goto(20,180)
for petal in range(9):
  painter.right(45)
  painter.forward(50)
  painter.stamp()
painter.penup()
painter.shape("circle")
painter.turtlesize(1.2)
painter.color("pink")
for flower in range(12):
    painter.goto(-3, 120)
    painter.setheading(flower * 30)
    painter.forward(35)
    painter.stamp()
wn = trtl.Screen()
wn.mainloop()